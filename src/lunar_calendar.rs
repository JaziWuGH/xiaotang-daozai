pub(crate) fn for_date(date: NaiveDate) -> Option<LunarDate> {
    let year = date.year();
    if !(FIRST_YEAR..=LAST_YEAR).contains(&year) {
        return None;
    }

    let row = (year - FIRST_DATA_YEAR) as usize;
    let (first_day, leap_month, lengths, terms) = YEARS[row];
    let (mut remaining, leap_month, lengths) = if date.ordinal0() < first_day {
        let (previous_first_day, previous_leap, previous_lengths, _) = YEARS[row - 1];
        let previous_new_year = NaiveDate::from_yo_opt(year - 1, previous_first_day + 1)?;
        (
            date.signed_duration_since(previous_new_year).num_days() as u32,
            previous_leap,
            previous_lengths,
        )
    } else {
        (date.ordinal0() - first_day, leap_month, lengths)
    };

    let first_term = date.month0() as usize * 2;
    let solar_term = (first_term..first_term + 2).find_map(|index| {
        let [tens, units] = [terms[index * 2], terms[index * 2 + 1]];
        let day = u32::from(tens - b'0') * 10 + u32::from(units - b'0');
        (day == date.day()).then_some(SOLAR_TERMS[index])
    });

    for (index, &length) in lengths.iter().enumerate() {
        let length = 29 + u32::from(length - b'0');
        if remaining < length {
            let in_leap_month = leap_month > 0 && index == leap_month;
            let month = index - usize::from(leap_month > 0 && index >= leap_month);
            let label = format!(
                "{}{}月{}",
                if in_leap_month { "闰" } else { "" },
                MONTH_NAMES[month],
                DAY_NAMES[remaining as usize],
            );
            return Some(LunarDate { label, solar_term });
        }
        remaining -= length;
    }
    None
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn dates_and_solar_terms_follow_the_selected_day() {
        for (year, month, day, label, solar_term) in [
            (2026, 1, 5, "十一月十七", Some("小寒")),
            (2026, 2, 16, "腊月廿九", None),
            (2026, 2, 17, "正月初一", None),
            (2026, 11, 21, "十月十三", None),
            (2026, 11, 22, "十月十四", Some("小雪")),
            (2026, 11, 23, "十月十五", None),
            (2025, 7, 24, "六月三十", None),
            (2025, 7, 25, "闰六月初一", None),
            (2033, 12, 22, "闰十一月初一", None),
            (1901, 1, 1, "十一月十一", None),
            (2100, 12, 31, "腊月初一", None),
        ] {
            let date = NaiveDate::from_ymd_opt(year, month, day).unwrap();
            let lunar = for_date(date).unwrap();
            assert_eq!(lunar.label, label, "{date}");
            assert_eq!(lunar.solar_term, solar_term, "{date}");
        }
    }

    #[test]
    fn every_supported_day_has_a_result() {
        let start = NaiveDate::from_ymd_opt(FIRST_YEAR, 1, 1).unwrap();
        let end = NaiveDate::from_ymd_opt(LAST_YEAR, 12, 31).unwrap();
        assert!(for_date(start.pred_opt().unwrap()).is_none());
        assert!(for_date(end.succ_opt().unwrap()).is_none());
        for date in start.iter_days().take_while(|&date| date <= end) {
            assert!(for_date(date).is_some(), "{date}");
        }
    }
}
